import { test, expect } from '@playwright/test';
import { installBrowserClock, freezeBrowserClock } from './clock';

test('debug map follows movement, gate revisions/routes, rejected probes and pause', async ({ page }) => {
  test.setTimeout(120_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await installBrowserClock(page); await page.goto('/');
  await expect(page.getByTestId('maze-debug')).toBeHidden();
  await page.getByRole('button', { name: 'F2 · Debug map' }).click();
  await expect(page.getByTestId('maze-debug')).toBeVisible();
  await expect(page.getByTestId('debug-room')).toHaveCount(25);
  await expect(page.locator('[data-edge-id]')).toHaveCount(31);
  await expect(page.getByTestId('debug-revision')).toHaveText('0');
  await page.getByRole('button', { name: 'Start exploring' }).click();
  await expect(page.getByTestId('hud')).toHaveAttribute('data-state', 'running');
  await expect.poll(() => page.evaluate(() => document.pointerLockElement?.id)).toBe('scene');
  await freezeBrowserClock(page);
  await page.keyboard.down('KeyW'); await page.clock.runFor(2700); await page.keyboard.up('KeyW'); await page.clock.runFor(120);
  const player = page.getByTestId('debug-player');
  expect(Number(await player.getAttribute('data-z'))).toBeCloseTo(Number(await page.getByTestId('position-z').textContent()), 2);
  await expect(page.getByTestId('debug-location')).toContainText('cell-2-1--cell-2-2');
  await page.locator('#scene').dispatchEvent('mousemove', { bubbles: true, movementX: 100, movementY: 0 });
  await page.clock.runFor(120); expect(Number(await player.getAttribute('data-yaw'))).toBeCloseTo(-0.2, 4);
  await page.locator('#scene').dispatchEvent('mousemove', { bubbles: true, movementX: -100, movementY: 0 });
  await page.keyboard.down('KeyW'); await page.clock.runFor(1300); await page.keyboard.up('KeyW'); await page.clock.runFor(120);
  await expect(page.getByTestId('debug-location')).toContainText('cell-2-1 ·');
  const northLink = page.locator('[data-edge-id="cell-2-1--cell-2-2"]');
  await expect(northLink).toHaveAttribute('data-route', 'true');
  await page.keyboard.press('KeyG'); await page.clock.runFor(200);
  await expect(page.getByTestId('debug-phase')).toHaveText('warning');
  await expect(page.getByTestId('debug-revision')).toHaveText('0');
  await expect(page.getByTestId('debug-gate-north')).toHaveAttribute('data-status', 'warning');
  // Sample beyond the 10 Hz diagnostic interval after closing begins.
  await page.clock.runFor(3300);
  await expect(page.getByTestId('debug-revision')).toHaveText('2');
  await expect(northLink).toHaveAttribute('data-open', 'false');
  await expect(northLink).toHaveAttribute('data-route', 'false');
  await expect(page.getByTestId('debug-gate-north')).toHaveAttribute('data-status', 'closing');
  const openness = Number(await page.getByTestId('debug-gate-north').getAttribute('data-openness'));
  expect(openness).toBeGreaterThan(0); expect(openness).toBeLessThan(1);
  await expect(page.getByTestId('debug-route')).toContainText('3 connections home');
  await page.clock.runFor(8000);
  await expect(page.getByTestId('debug-phase')).toHaveText('idle');
  await expect(page.getByTestId('debug-gate-north')).toHaveAttribute('x', '-2');
  const before = await page.locator('[data-edge-id]').evaluateAll(lines => lines.map(line => line.getAttribute('data-open')));
  await page.keyboard.press('KeyV'); await page.clock.runFor(120);
  await expect(page.getByTestId('debug-probe-result')).toHaveAttribute('data-result', 'rejected');
  await expect(page.getByTestId('debug-probe-result')).toContainText('24/25');
  await expect(page.getByTestId('debug-probe-result')).toBeInViewport({ ratio: 1 });
  expect(await page.locator('[data-edge-id]').evaluateAll(lines => lines.map(line => line.getAttribute('data-open')))).toEqual(before);
  await expect(page.getByTestId('debug-revision')).toHaveText('2');
  await expect(page.getByTestId('shift-count')).toHaveText('1 shift');
  await page.keyboard.press('Escape'); await expect(page.getByTestId('hud')).toHaveAttribute('data-state', 'paused');
  await page.clock.runFor(120); const frozen = await player.getAttribute('data-z');
  await page.clock.runFor(1500); expect(await player.getAttribute('data-z')).toBe(frozen);
  await page.keyboard.press('F2'); await expect(page.getByTestId('maze-debug')).toBeHidden();
  await page.keyboard.press('F2'); await expect(page.getByTestId('maze-debug')).toBeVisible();
  await page.getByRole('button', { name: 'Probe isolation' }).click();
  await expect(page.getByTestId('debug-probe-result')).toContainText('No changes applied');
  expect(errors).toEqual([]);
});
